<#
.SYNOPSIS
    Copies openSMILE header files to a target directory.

.DESCRIPTION
    This script copies all files under 'src\include' of the openSMILE repository to a target include directory,
    maintaining the original directory structure for proper include path resolution.
    License files of bundled third-party code are kept, while CMake templates ('*.in') are skipped.
    It also copies 'core\git_version.hpp', which is generated by CMake into the build directory instead of the source tree.

.PARAMETER OpenSmileRoot
    The root directory of the openSMILE repository. Must contain 'src\include' subdirectory.

.PARAMETER BuildDir
    The CMake build directory. Must contain the generated 'src\include\core\git_version.hpp'.
    Defaults to 'build' under OpenSmileRoot.

.PARAMETER TargetDir
    The target directory for header files. Defaults to 'include' in the script directory.
    If the directory exists, it will be deleted and recreated.

.EXAMPLE
    .\copy_headers.ps1 -OpenSmileRoot "D:\Project\Other\opensmile"
    Copies headers from openSMILE to the default 'include' directory.

.EXAMPLE
    .\copy_headers.ps1 -OpenSmileRoot "D:\Project\Other\opensmile" -BuildDir "D:\Build\opensmile"
    Copies headers using a build directory outside the source tree.

.NOTES
    Exit codes:
    0 - Success
    1 - Some files failed to copy
#>

param(
    [Parameter(Mandatory=$true)]
    [ValidateScript({
        if(-Not (Test-Path $_)) {
            throw "openSMILE root directory does not exist: $_"
        }
        if(-Not (Test-Path (Join-Path $_ "src\include"))) {
            throw "Invalid openSMILE root directory. 'src\include' not found in: $_"
        }
        return $true
    })]
    [string]$OpenSmileRoot,
    [string]$BuildDir,
    [string]$TargetDir = "include"
)


$openSmileRootPath = Resolve-Path $OpenSmileRoot
$buildPath = if ([string]::IsNullOrEmpty($BuildDir)) {
    Join-Path $openSmileRootPath "build"
} else {
    Resolve-Path $BuildDir
}
$targetPath = if([System.IO.Path]::IsPathRooted($TargetDir)) {
    $TargetDir
} else {
    Join-Path $PSScriptRoot $TargetDir
}

$sourceIncludePath = (Join-Path $openSmileRootPath "src\include").TrimEnd("\")
$generatedVersionHeader = Join-Path $buildPath "src\include\core\git_version.hpp"

# Fail before touching the target directory, so a wrong BuildDir does not leave an incomplete include tree behind.
if (-Not (Test-Path $generatedVersionHeader)) {
    Write-Host "Error: Generated header not found: $generatedVersionHeader. Run CMake configure first." -ForegroundColor Red
    exit 1
}


if (Test-Path $targetPath) {
    Write-Host "Cleaning existing directory: $targetPath"
    Remove-Item -Path $targetPath -Recurse -Force
}

Write-Host "Copying openSMILE headers to $targetPath"

New-Item -ItemType Directory -Path $targetPath -Force | Out-Null

$totalFilesCopied = 0
$failedCopies = @()

$headerFiles = Get-ChildItem -Path $sourceIncludePath -Exclude "*.in" -Recurse -File

foreach ($headerFile in $headerFiles) {
    try {
        $relativePath = $headerFile.FullName.Substring($sourceIncludePath.Length).TrimStart("\")
        $targetFilePath = Join-Path $targetPath $relativePath
        $targetFileDir = Split-Path $targetFilePath -Parent

        if (-Not (Test-Path $targetFileDir)) {
            New-Item -ItemType Directory -Path $targetFileDir -Force | Out-Null
        }

        Copy-Item -Path $headerFile.FullName -Destination $targetFilePath -Force
        $totalFilesCopied++
    }
    catch {
        $failedCopies += @{
            Source = $headerFile.FullName
            Error = $_.Exception.Message
        }
    }
}

try {
    $targetCorePath = Join-Path $targetPath "core"
    New-Item -ItemType Directory -Path $targetCorePath -Force | Out-Null
    Copy-Item -Path $generatedVersionHeader -Destination (Join-Path $targetCorePath "git_version.hpp") -Force
    $totalFilesCopied++
}
catch {
    $failedCopies += @{
        Source = $generatedVersionHeader
        Error = $_.Exception.Message
    }
}

Write-Host "Copied $totalFilesCopied header files"

if ($failedCopies.Count -gt 0) {
    Write-Host "Warning: $($failedCopies.Count) files failed to copy" -ForegroundColor Yellow
    foreach ($failure in $failedCopies) {
        Write-Host "  $($failure.Source): $($failure.Error)" -ForegroundColor Yellow
    }
    exit 1
}
